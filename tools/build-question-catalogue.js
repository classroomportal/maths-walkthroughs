// Builds plans/question-catalogue.js: every maths walkthrough question the lesson-mapping
// page can offer. Run from the repo root after adding or changing walkthroughs:
//   node tools/build-question-catalogue.js
const fs = require('fs');
const path = require('path');

const FOLDERS = ['year07', 'year08', 'year09', 'year10', 'year11', 'year12', 'addmaths', 'furthermaths',
  'ext_mth', 'bridge_mth', 'bridge_mth_y8', 'bridge_mth_y9', 'bridge_mth_y10', 'bridge_mth_y11', 'bridge_mth_y12',
  'deepdive/maths/algebra', 'deepdive/maths/geometry', 'deepdive/maths/number'];

// Evaluate an array literal from a page, with any identifiers it uses (draw functions,
// tryIt(), helpers) replaced by harmless stubs.
function evalArray(src) {
  // A stand-in that can be called, indexed, iterated or printed without failing
  const stub = new Proxy(function () {}, {
    get: (_, k) => (k === Symbol.toPrimitive ? h => (h === 'string' ? '' : 0) : k === Symbol.iterator ? function* () {} : k === 'length' ? 0 : stub),
    apply: () => stub,
    construct: () => stub,
  });
  const scope = new Proxy({}, { has: () => true, get: (_, k) => (k === Symbol.unscopables ? undefined : k in globalThis ? globalThis[k] : stub) });
  return Function('scope', 'with (scope) { return (' + src + '); }')(scope);
}

function arrayAfter(s, marker) {
  const i = s.indexOf(marker);
  if (i < 0) return null;
  let j = s.indexOf('[', i), depth = 0, q = null;
  for (let k = j; k < s.length; k++) {
    const c = s[k];
    if (q) { if (c === '\\') k++; else if (c === q) q = null; continue; }
    if (c === "'" || c === '"' || c === '`') q = c;
    else if (c === '[') depth++;
    else if (c === ']' && --depth === 0) return s.slice(j, k + 1);
  }
  return null;
}

const ENT = { amp: '&', middot: '·', mdash: '—', ndash: '–', nbsp: ' ', rsquo: '’', lsquo: '‘', quot: '"', apos: "'", lt: '<', gt: '>', times: '×', divide: '÷', minus: '−', sup2: '²', sup3: '³' };
const decode = t => t.replace(/&(#\d+|#x[0-9a-f]+|[a-z0-9]+);/gi, (m, e) =>
  e[0] === '#' ? String.fromCodePoint(e[1] === 'x' || e[1] === 'X' ? parseInt(e.slice(2), 16) : +e.slice(1)) : (ENT[e.toLowerCase()] || m));
const plain = t => decode(String(t || '').replace(/<[^>]+>/g, '')).replace(/\s+/g, ' ').trim();
// "Algebra · Year 7 · Maths Walkthroughs" -> "Algebra · Year 7"
const cleanTitle = t => plain(t).replace(/\s*[·—-]\s*Maths Walkthroughs\s*$/, '').replace(/\s+[—-]\s+(Bridge Maths\s+[—-]\s+)?ABC.*$/, '');
const out = [];
for (const folder of FOLDERS) {
  if (!fs.existsSync(folder)) continue;
  for (const name of fs.readdirSync(folder).filter(n => n.endsWith('.html')).sort()) {
    const file = folder + '/' + name;
    const s = fs.readFileSync(file, 'utf8');
    const title = cleanTitle((s.match(/<title>([^<]*)/) || [])[1]);
    const entry = { file, title: folder.startsWith('bridge_') && !/bridge/i.test(title) ? title + ' · Bridge' : title, questions: [], filterable: false };
    try {
      const qs = arrayAfter(s, 'var QS=[') || arrayAfter(s, 'var QS = [') || arrayAfter(s, 'const QS=[') || arrayAfter(s, 'const QS = [');
      if (qs) {
        entry.questions = evalArray(qs).map(q => ({ t: plain(q.ti), l: q.lv || '', s: plain(q.su).slice(0, 140) }));
        entry.filterable = s.includes('abcQuestionNumbers'); // standard engine with ?only= and ?q= support
      } else if (/\bQS\s*=\s*\[/.test(s)) {
        // Fallback when the array can't be isolated: read the question headers directly
        const dec = x => { try { return JSON.parse('"' + x.replace(/\\'/g, "'").replace(/"/g, '\\"') + '"'); } catch (e) { return x; } };
        const re = /\{\s*ey\s*:\s*'((?:\\.|[^'\\])*)'\s*,\s*ti\s*:\s*'((?:\\.|[^'\\])*)'\s*,\s*su\s*:\s*'((?:\\.|[^'\\])*)'([^{]{0,40})/g;
        let m;
        while ((m = re.exec(s))) {
          const lv = (m[4].match(/lv\s*:\s*'([FE])'/) || [])[1] || '';
          entry.questions.push({ t: plain(dec(m[2])), l: lv, s: plain(dec(m[3])).slice(0, 140) });
        }
        entry.filterable = entry.questions.length > 0 && s.includes('abcQuestionNumbers');
      } else {
        const bq = arrayAfter(s, 'const QUESTIONS = [');
        if (bq) entry.questions = evalArray(bq).map(q => ({ t: plain(q.title), l: '', s: '' }));
      }
    } catch (e) {
      console.warn('skipped questions for', file, '-', e.message);
    }
    // Older pages put the level badge inside the title ("... F"); move it to the level field
    entry.questions.forEach(q => { const m = q.t.match(/^(.*\S)\s+(F|E)$/); if (m) { q.t = m[1]; if (!q.l) q.l = m[2]; } });
    out.push(entry);
  }
}
const body = '// Generated by tools/build-question-catalogue.js - do not edit by hand.\n' +
  'window.QUESTION_CATALOGUE = ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join('plans', 'question-catalogue.js'), body);
console.log('files', out.length, '| questions', out.reduce((a, e) => a + e.questions.length, 0),
  '| filterable files', out.filter(e => e.filterable).length);
